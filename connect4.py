import numpy as np
import pygame
import sys
import math

BLUE = (0,0,255)
BLACK = (0,0,0)
RED = (255,0,0)
YELLOW = (255,255,0)

ROW_COUNT = 6
COLUMN_COUNT = 7

def create_board():
	board = np.zeros((ROW_COUNT,COLUMN_COUNT))
	return board
# Эта функция создает игровое поле, представляющее собой двумерный массив (либо матрицу), заполненный нулями.
# - ROW_COUNT и COLUMN_COUNT — это размеры поля, скорее всего глобальные переменные, которые ты определил ранее.
# - np.zeros((ROW_COUNT, COLUMN_COUNT)) создаёт массив с заданными размерами, заполненный нулями, что означает, что все ячейки пустые.

def drop_piece(board, row, col, piece):
	board[row][col] = piece
# Эта функция отвечает за «падение» фишки на игровом поле.
# - board — это текущее состояние игрового поля.
# - row и col — это координаты, куда ты хочешь поместить фишку.
# - piece — это сама фишка (например, 1 для игрока 1 и 2 для игрока 2).
# При вызове этой функции определённая позиция на доске заменяется значением piece.

def is_valid_location(board, col):
	return board[ROW_COUNT-1][col] == 0
# Эта функция проверяет, можно ли поместить фишку в заданный столбец (col).
# - Она возвращает True, если в самом нижнем ряду (ROW_COUNT-1) указанного столбца (col) стоит 0, что означает, что незанятое место, и False в противном случае.
def get_next_open_row(board, col):
	for r in range(ROW_COUNT):
		if board[r][col] == 0:
			return r
# Эта функция ищет самую нижнюю доступную строку в столбце (col).
# - Она перебирает все строки в столбце и возвращает индекс (номер строки) первой пустой ячейки (которая имеет значение 0).
# Если вся колонка заполнена, функция может просто закончиться без возврата.

def print_board(board):
	print(np.flip(board, 0))
# Эта функция выводит текущее состояние игрового поля.
# - np.flip(board, 0) переворачивает поле вертикально.
# Это делается для того, чтобы выводить поле так, как делает это игрок, показывая нижнюю часть доски (где происходит падение фишек) внизу, а верхнюю — сверху.

def winning_move(board, piece):
	# Проверка по горизинтоли на победу
	for c in range(COLUMN_COUNT-3):
		# Мы перебираем столбцы игрового поля, начиная с 0 до COLUMN_COUNT-3.
		# Это сделано для того, чтобы можно было проверить группы из 4 ячеек
		# (если бы мы проверяли до COLUMN_COUNT, то возникла бы ошибка индексации, когда мы пытаемся получить элементы c+1, c+2 и c+3).
		for r in range(ROW_COUNT):
			 # Внутренний цикл перебирает строки от 0 до ROW_COUNT. Таким образом, мы проверяем каждую строку отдельно на наличие выигрышной комбинации.
			if board[r][c] == piece and board[r][c+1] == piece and board[r][c+2] == piece and board[r][c+3] == piece:
				# Это условие проверяет, равны ли значения в текущей строке для ячеек от c до c+3.
				# Если все 4 ячейки содержат одно и то же значение (piece), значит, игрок, который совершил этот ход, победил.
				return True
# Если условие выполняется (т.е. найдена выигрышная комбинация), функция возвращает True. Это означает, что этот игрок выиграл.

	# Проверка по вертикали на победу
	for c in range(COLUMN_COUNT):
		for r in range(ROW_COUNT-3):
			if board[r][c] == piece and board[r+1][c] == piece and board[r+2][c] == piece and board[r+3][c] == piece:
				return True

	# Проверка положительной диагонали
	for c in range(COLUMN_COUNT-3):
		for r in range(ROW_COUNT-3):
			if board[r][c] == piece and board[r+1][c+1] == piece and board[r+2][c+2] == piece and board[r+3][c+3] == piece:
				return True

	# Проверка отрицатильной диагонал
	for c in range(COLUMN_COUNT-3):
		for r in range(3, ROW_COUNT):
			if board[r][c] == piece and board[r-1][c+1] == piece and board[r-2][c+2] == piece and board[r-3][c+3] == piece:
				return True

def draw_board(board):
	for c in range(COLUMN_COUNT):
		for r in range(ROW_COUNT):
			pygame.draw.rect(screen, BLUE, (c*SQUARESIZE, r*SQUARESIZE+SQUARESIZE, SQUARESIZE, SQUARESIZE))
			pygame.draw.circle(screen, BLACK, (int(c*SQUARESIZE+SQUARESIZE/2), int(r*SQUARESIZE+SQUARESIZE+SQUARESIZE/2)), RADIUS)
	# - Эти циклы перебирают все колонки(c) и	строки(r) доски.
	# - pygame.draw.rect рисует синий прямоугольник(клетку) для каждой позиции.
	# - pygame.draw.circle рисует черный круг	внутри каждой клетки.Это может служить фоном для фишек.
	for c in range(COLUMN_COUNT):
		for r in range(ROW_COUNT):		
			if board[r][c] == 1:
				pygame.draw.circle(screen, RED, (int(c*SQUARESIZE+SQUARESIZE/2), height-int(r*SQUARESIZE+SQUARESIZE/2)), RADIUS)
			elif board[r][c] == 2: 
				pygame.draw.circle(screen, YELLOW, (int(c*SQUARESIZE+SQUARESIZE/2), height-int(r*SQUARESIZE+SQUARESIZE/2)), RADIUS)
	# - Здесь	снова перебираются колонки и строки.Но в этом случае проверяется значение в	board на каждой	позиции(board[r][c]).
	# - Если значение	1, отрисовывается красный круг(это может быть фишка	первого	игрока), если 2 — желтый круг(фишка	второго	игрока).
	# - height - int(...)	используется для корректного позиционирования круга	на экране, так как координата y	в Pygame увеличивается вниз.

	pygame.display.update() # - Эта строка обновляет экран, чтобы все изменения, которые были сделаны с помощью рисования, стали видимыми.
# Без этого обновления на экране ничего не изменится.

board = create_board()
print_board(board)
# - Здесь всё так же, как и в предыдущем коде: создаётся игровое поле и печатается его текущее состояние.
game_over = False
turn = 0
# - Прежде всего, мы указываем, что игра ещё не завершилась (game_over = False), и что сейчас ход первого игрока (turn = 0).
pygame.init()
# - Это та же функция из предыдущего блока кода, которая инициирует Pygame, чтобы наше игровое окно работало.
SQUARESIZE = 100
# - Каждая клетка игрового поля всё та же — 100 пикселей на 100 пикселей.
width = COLUMN_COUNT * SQUARESIZE
height = (ROW_COUNT+1) * SQUARESIZE
# - Ширина (width) берётся из количества колонок,
# а высота (height) — из количества строк с учётом дополнительной строки для каких-то игровых элементов (например, для отображения счета).
size = (width, height)
# - Тут создаётся кортеж size с размерами окна, которые позже будут использованы при его создании.

RADIUS = int(SQUARESIZE/2 - 5)
# Здесь мы устанавливаем радиус для фишек, которые будут размещаться на игровом поле.
# Мы берём половину SQUARESIZE и вычитаем 5 пикселей, чтобы фишки не заполняли клетку полностью и выглядели аккуратно.
screen = pygame.display.set_mode(size)
# - Эта функция создаёт игровое окно с указанным размером size, используя Pygame. Теперь у нас есть пространство для игры
draw_board(board)
pygame.display.update()
# - Вызов draw_board(board) отвечает за отрисовку игрового поля на экране, добавляя визуальные элементы в соответствии с содержимым массива board.
# А затем pygame.display.update() обновляет экран, чтобы все изменения отображались.
myfont = pygame.font.SysFont("monospace", 60)
# - Здесь мы создаём шрифт с использованием системного шрифта "monospace" с размером 60.
# Этот шрифт можно будет использовать для отображения текста на экране, например, для победных сообщений или подсчёта очков
while not game_over:
	# Этот цикл будет продолжаться до тех	пор, пока переменная game_over не станет равной True.Это означает, что игра активно идет.
	for event in pygame.event.get():
		# Здесь мы получаем все события, которые происходят в игре, например, нажатия клавиш или движения мыши.
		if event.type == pygame.QUIT:
			sys.exit()
		# Проверяем, закрыл ли	пользователь окно игры.Если да, вызываем sys.exit(), чтобы завершить программу.
		if event.type == pygame.MOUSEMOTION:
			# Этот блок	срабатывает, когда мышь движется по экрану.
			pygame.draw.rect(screen, BLACK, (0,0, width, SQUARESIZE))
			# Здесь мы рисуем	черный прямоугольник, чтобы "очистить" область, где	будет отображаться фишка.Это позволяет избежать оставления следов от предыдущих	движений.
			posx = event.pos[0]
			# Получаем текущую координату	мыши по оси x.Это то место, где	мы хотим нарисовать круг(фишку).
			if turn == 0:
				# Если сейчас	ход	первого	игрока(например, красный), мы рисуем красный круг.
				pygame.draw.circle(screen, RED, (posx, int(SQUARESIZE/2)), RADIUS)
				# Рисуем красный круг по координате posx и по	центру высоты прямоугольника(половина SQUARESIZE).
			else: 
				pygame.draw.circle(screen, YELLOW, (posx, int(SQUARESIZE/2)), RADIUS)
		pygame.display.update()
		# Эта команда в конце обновляет экран, чтобы отобразить все наши изменения(включая движение фишек).
		if event.type == pygame.MOUSEBUTTONDOWN:
			   # Здесь проверяется, произошло ли событие нажатия кнопки мыши. Если да, то выполняется код внутри этого блока.
			pygame.draw.rect(screen, BLACK, (0,0, width, SQUARESIZE))
			   # Здесь проверяется, произошло ли событие нажатия кнопки мыши. Если да, то выполняется код внутри этого блока.
			print(event.pos)
			   # Эта строка выводит в консоль позицию курсора мыши в момент нажатия. event.pos возвращает координаты (x, y) нажима.
			# Запрос на ход красного
			if turn == 0:
				posx = event.pos[0]
				col = int(math.floor(posx/SQUARESIZE))
				# Получаем координату x нажатия и делим на размер квадратов в игровом поле SQUARESIZE, чтобы определить, в какой столбец была сделана попытка сделать ход.

				if is_valid_location(board, col):
					# Здесь проверяется, можно ли сделать ход в выбранный столбец. Функция is_valid_location должна возвращать True, если в столбце есть свободные ячейки.
					row = get_next_open_row(board, col)
					drop_piece(board, row, col, 1)
						# Если ход возможен, то определяем, в какую строку мы можем поместить фишку
						# (используя функцию get_next_open_row) и добавляем фишку игрока 1 (красного) с помощью функции drop_piece.
					if winning_move(board, 1):
						# Здесь проверяется, не выиграл ли красный игрок после своего хода.
						# Функция winning_move должна вернуть True, если есть четыре фишки в ряд для красного игрока.
						label = myfont.render("Красный победил!!", 1, RED)
						screen.blit(label, (40,10))
						game_over = True
					# Если игрок выиграл, создается текстовое сообщение с помощью myfont.render,
					# а затем оно отображается на экране с помощью screen.blit. game_over устанавливается в True для того, чтобы завершить игру

			# # Запрос на ход желтого
			else:				
				posx = event.pos[0]
				# Здесь мы получаем координату x, которую указал пользователь, когда кликнул мышкой.
				col = int(math.floor(posx/SQUARESIZE))
				# Делим позицию x на размер квадрата (SQUARESIZE), чтобы узнать, в какой именно столбец игрок хочет сделать ход.
				# Используем math.floor, чтобы округлить вниз до ближайшего целого числа.
				if is_valid_location(board, col):
					# Проверяем, можно ли сделать ход в выбранном столбце, используя функцию is_valid_location. Если столбец не заполнен полностью, то возвращает True.
					row = get_next_open_row(board, col)
					# Если ход возможен, мы находим ближайшую свободную строку в выбранном столбце с помощью функции get_next_open_row.
					drop_piece(board, row, col, 2)
						# Здесь мы добавляем фишку второго игрока (жёлтого) в таблицу (board) в найденную строку и столбец, используя функцию drop_piece.
					if winning_move(board, 2):
						# После добавления фишки проверяем, не выиграл ли жёлтый игрок, используя функцию winning_move. Если функция возвращает True, значит, он выиграл.
						label = myfont.render("Жёлтый победил!!", 1, YELLOW)
						screen.blit(label, (40,10))
						game_over = True
						#    Если игрок выиграл, мы создаем текстовое сообщение "Жёлтый победил", рисуем его на экране с помощью screen.blit.
						# Устанавливаем переменную game_over в True, чтобы остановить игру.

			print_board(board)
			draw_board(board)
			# Эти функции отвечают за отображение текущего состояния игровой доски на экране.
			#    print_board(board) может выводить состояние в консоль, а draw_board(board) будет выстраивать визуальное представление на экране.

			turn += 1
			turn = turn % 2
			# Увеличиваем номер хода, и затем используем модульное деление на 2, чтобы возвращаться к 0 после второго игрока.
			# Это обеспечивает чередование ходов между двумя игроками (0 и 1).
			if game_over:
				pygame.time.wait(3000)
				# (game_over равно True), программа приостанавливает выполнение на 3000 миллисекунд (или 3 секунды) перед тем,
				# как продолжить (обычно это время дается игрокам, чтобы увидеть сообщение о победе).